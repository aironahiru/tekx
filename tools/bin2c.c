/*
 * bin2c: embed files as C arrays.
 *
 *   bin2c file... > assets.c
 *
 * Each file becomes an entry in a table keyed by its base name, so the
 * tekx binary carries its fonts and hyphenation patterns with it.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *
basename_of(const char *p)
{
	const char *s = strrchr(p, '/');
	return s ? s + 1 : p;
}

int
main(int argc, char **argv)
{
	int i, c;
	long n;
	FILE *f;

	printf("/* generated by tools/bin2c -- do not edit */\n");
	printf("#include \"tekx.h\"\n\n");
	for (i = 1; i < argc; i++) {
		if ((f = fopen(argv[i], "rb")) == NULL) {
			perror(argv[i]);
			return 1;
		}
		printf("static const unsigned char a%d[] = {", i);
		for (n = 0; (c = getc(f)) != EOF; n++)
			printf("%s%d,", n % 24 ? "" : "\n", c);
		printf("0\n};\n");
		fclose(f);
	}
	printf("\nconst Asset assets[] = {\n");
	for (i = 1; i < argc; i++)
		printf("\t{\"%s\", a%d, sizeof a%d - 1},\n",
		    basename_of(argv[i]), i, i);
	printf("\t{0, 0, 0}\n};\n");
	return 0;
}
